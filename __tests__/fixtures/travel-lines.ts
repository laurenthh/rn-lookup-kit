import type { TravelIntent } from '../../src/travel'

// Real travel-list lines with the outcome a user would want from the lookup:
// the intent kind and its fields. `none` means "deliberately no link". Lines
// where today's code disagrees are listed in KNOWN_GAPS below.
//
// Conventions: `flight.to` keeps a trailing date/time as typed (19 decision)
// but not people counts, prices or flight numbers; ground `to`/`from` are the
// intent's values (time phrases are stripped at link time); for a combined
// item the desired single outcome is the first leg/noun as written; the
// 14/18/19 user decisions are kept as desired (bare mode word → place, aman/
// taj/peninsula need the `hotel` tag, Airbnb → Maps, "book hotel" → none).
export type TravelLine =
  | [text: string, want: TravelIntent]
  | [text: string, want: TravelIntent, tags: string[]]

const flight = (to: string, from: string | null = null): TravelIntent => ({
  kind: 'flight',
  to,
  from,
})
const transit = (to: string, from: string | null = null): TravelIntent => ({
  kind: 'ground',
  to,
  from,
  mode: 'transit',
})
const driving = (to: string, from: string | null = null): TravelIntent => ({
  kind: 'ground',
  to,
  from,
  mode: 'driving',
})
const walking = (to: string, from: string | null = null): TravelIntent => ({
  kind: 'ground',
  to,
  from,
  mode: 'walking',
})
const bicycling = (to: string, from: string | null = null): TravelIntent => ({
  kind: 'ground',
  to,
  from,
  mode: 'bicycling',
})
const book = (name: string, inCity: boolean): TravelIntent => ({
  kind: 'book',
  name,
  inCity,
})
const checkin = (name: string): TravelIntent => ({ kind: 'checkin', name })
const dine = (name: string): TravelIntent => ({ kind: 'dine', name })
const STAY: TravelIntent = { kind: 'stay' }
const PLACE: TravelIntent = { kind: 'place' }
